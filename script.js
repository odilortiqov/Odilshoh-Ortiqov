// TILNI ALMASHTIRISH

const language = document.querySelector(".language");
const languageButton = document.getElementById("languageButton");
const languageMenu = document.getElementById("languageMenu");
const currentLanguage = document.getElementById("currentLanguage");

function setLanguage(lang) {
    if (!translations[lang]) return;

    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (translations[lang][key] !== undefined) {
            element.textContent = translations[lang][key];
        }
    });

    currentLanguage.textContent = lang.toUpperCase();

    languageMenu.querySelectorAll("button").forEach(button => {
        button.classList.toggle("selected", button.dataset.lang === lang);
    });

    localStorage.setItem("portfolioLanguage", lang);

    language.classList.remove("open");
    languageButton.setAttribute("aria-expanded", "false");
}


// TIL MENYUSINI OCHISH VA YOPISH

languageButton.addEventListener("click", event => {
    event.stopPropagation();

    const isOpen = language.classList.toggle("open");
    languageButton.setAttribute("aria-expanded", String(isOpen));
});

languageMenu.querySelectorAll("button").forEach(button => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.lang);
    });
});

document.addEventListener("click", event => {
    if (!language.contains(event.target)) {
        language.classList.remove("open");
        languageButton.setAttribute("aria-expanded", "false");
    }
});


// MOBIL MENYU

const menuToggle = document.getElementById("menuToggle");
const nav = document.getElementById("nav");

menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("open");

    menuToggle.setAttribute("aria-expanded", String(isOpen));
    menuToggle.setAttribute(
        "aria-label",
        isOpen ? "Menyuni yopish" : "Menyuni ochish"
    );

    menuToggle.textContent = isOpen ? "✕" : "☰";
});

nav.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
        nav.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
        menuToggle.textContent = "☰";
    });
});


// RASMLAR TOPILMAGANDA ZAXIRA BELGISINI KO‘RSATISH

document.querySelectorAll(".hero-photo img, .achievement-image img, .university-image img")
    .forEach(img => {
        const handleImageError = () => {
            img.style.display = "none";

            const fallback = img.parentElement.querySelector(".photo-placeholder, .image-fallback");

            if (fallback) {
                fallback.style.display = "grid";
            }
        };

        img.addEventListener("error", handleImageError);

        if (img.complete && img.naturalWidth === 0) {
            handleImageError();
        }
    });


// FAOL MENYU BANDINI ANIQLASH

const sections = document.querySelectorAll("main section[id]");
const navLinks = document.querySelectorAll(".nav-link");

if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver(entries => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                navLinks.forEach(link => {
                    link.classList.toggle(
                        "active",
                        link.getAttribute("href") === `#${entry.target.id}`
                    );
                });
            }
        });
    }, {
        rootMargin: "-25% 0px -60% 0px"
    });

    sections.forEach(section => observer.observe(section));
}


